'use strict';
const {app,BrowserWindow,ipcMain,session}=require('electron');
const path=require('node:path'),fs=require('node:fs'),os=require('node:os'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const root=path.resolve(__dirname,'..'),work=fs.mkdtempSync(path.join(os.tmpdir(),'mtg-import-'));
let win, finishExport;const requests=[];
async function run(){
 app.setPath('userData',path.join(work,'electron'));await app.whenReady();
 session.defaultSession.webRequest.onBeforeRequest({urls:['http://*/*','https://*/*']},(_d,done)=>done({cancel:true}));
 ipcMain.handle('card-export',()=>new Promise(resolve=>{finishExport=resolve;}));
 ipcMain.handle('updates:get-state',()=>({enabled:false,status:'idle'}));
 const image=pathToFileURL(path.join(root,'test/images/1_mtg.png')).href;
 ipcMain.handle('card-request',(_e,payload)=>{requests.push(payload);return {entries:[{id:'row-1',name:'Custom art',qty:2,printing:{id:'custom',name:'Custom art',custom:true,paired:true,faces:[{url:image},{url:image}]}}],errors:[]};});
 ipcMain.handle('select-card-input',()=>({path:'/deck-é.csv',text:'name,Set\nCustom art,ltr'}));
 win=new BrowserWindow({show:false,width:1200,height:1000,webPreferences:{nodeIntegration:true,contextIsolation:false}});
 const js=code=>win.webContents.executeJavaScript(code);
 const wait=async predicate=>{const end=Date.now()+10000;while(Date.now()<end){if(await js(predicate))return;await new Promise(r=>setTimeout(r,40));}throw Error(await js('document.body.innerText'));};
 await win.loadFile(path.join(root,'GUI/CardList/decklist.html'),{query:{game:'mtg'}});
 await wait('!document.getElementById("longText").disabled');
 await js("document.getElementById('gameOptionsBtn').click()");await wait("!!document.getElementById('game-option-format')");
 await js("document.getElementById('game-option-format').value='cubecobra_csv';document.getElementById('gameOptionsContinue').click()");
 await js("[...document.querySelectorAll('button')].find(b=>b.textContent==='Open deck file').click()");
 await wait("!document.getElementById('nextCreatePdfBtn').disabled");
 assert.equal(requests[0].format,'cubecobra_csv');assert.equal(requests[0].input.value,'/deck-é.csv');
 assert.match(await js('document.body.innerText'),/Custom image/);
 assert.equal(await js("document.getElementById('longText').value"),'name,Set\nCustom art,ltr');
 await js("document.getElementById('mtg-tokens').checked=true;[...document.querySelectorAll('button')].find(b=>b.textContent==='Apply preferences').click()");
 assert.equal(await js("document.getElementById('nextCreatePdfBtn').disabled"),true);
 await js("document.getElementById('longForm').requestSubmit()");await wait("!document.getElementById('nextCreatePdfBtn').disabled");
 assert.equal(requests.at(-1).options.tokens,true);
 assert.equal(requests.at(-1).input.value,'/deck-é.csv');
 await js("document.getElementById('nextCreatePdfBtn').click()");
 await wait("document.getElementById('nextCreatePdfBtn').disabled");
 assert.equal(await js("[...document.querySelectorAll('#longForm button,#longForm input,#longForm textarea')].every(control=>control.disabled)"),true);
 finishExport({canceled:true});
 await wait("!document.getElementById('nextCreatePdfBtn').disabled");
 assert.equal(await js("document.getElementById('mtg-tokens').disabled"),false);
 win.destroy();app.quit();console.log('MTG import/preferences smoke passed.');
}
run().catch(e=>{console.error(e);if(win)win.destroy();app.exit(1);});
